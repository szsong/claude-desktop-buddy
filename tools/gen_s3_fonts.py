#!/usr/bin/env python3
"""Generate s3/fonts.h: the DM Sans message font of the S3 build, in the VLW
format LovyanGFX loads, with anti-aliased edges (8-bit alpha per pixel) and the
ISO-8859-1 glyphs. "N px" is the full glyph height (ascent + descent). Same
font and size as Claudinho's message lines.

Needs Pillow (pip install pillow). Usage: python3 tools/gen_s3_fonts.py
"""
import struct
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "s3" / "fonts.h"
CHARS = list(range(32, 127)) + list(range(160, 256))
FONTS = [("FONT_MSG", "Regular", 26)]   # C name, weight (variable font), total height in px


def open_font(weight, size):
    f = ImageFont.truetype(str(HERE / "fonts" / "DMSans.ttf"), size)
    f.set_variation_by_name(weight)
    return f


def size_for(weight, height):
    """Largest size whose ascent + descent fits the requested height."""
    best = 4
    for s in range(4, height * 2):
        a, d = open_font(weight, s).getmetrics()
        if a + d <= height: best = s
    return best


def vlw(weight, height):
    f = open_font(weight, size_for(weight, height))
    asc, desc = f.getmetrics()
    glyphs, bitmaps = [], []
    for c in CHARS:
        ch = chr(c)
        advance = round(f.getlength(ch))
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")       # relative to the baseline
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
            bitmaps.append(im.tobytes())
        else:
            w = h = 0; bitmaps.append(b"")
        glyphs.append((c, h, w, advance, -y0 if h else 0, x0 if w else 0))
    out = struct.pack(">6i", len(glyphs), 11, asc + desc, 0, asc, desc)
    for c, h, w, adv, dy, dx in glyphs:
        out += struct.pack(">7i", c, h, w, adv, dy, dx, 0)
    return out + b"".join(bitmaps)


def main():
    lines = ["// Generated by tools/gen_s3_fonts.py (DM Sans, OFL). Do not edit.", "#pragma once", "#include <stdint.h>", ""]
    for name, weight, height in FONTS:
        data = vlw(weight, height)
        lines.append("static const uint8_t %s[%d] PROGMEM = {" % (name, len(data)))
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        print("%s: DM Sans %s %d px -> %d bytes" % (name, weight, height, len(data)))
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
